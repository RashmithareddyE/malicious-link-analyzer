"""
ml_classifier.py - Machine-learning URL classification (SAFE / SUSPICIOUS / MALICIOUS).

IMPORTANT HONESTY NOTE
----------------------
No real phishing dataset is bundled with this project. dataset/urls.csv is a
SYNTHETIC DEMONSTRATION dataset generated by generate_sample_dataset() below,
using reserved/example domains only. Metrics measured on it show that the
training pipeline works - they do NOT represent real-world detection accuracy.
To get realistic results, replace dataset/urls.csv with a real labelled dataset
(columns: url,label) and retrain.

Command line (run from the project root):
    python -m modules.ml_classifier generate   # create dataset/urls.csv
    python -m modules.ml_classifier train      # train + save model + metrics
    python -m modules.ml_classifier all        # both
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, confusion_matrix,
                             precision_recall_fscore_support)
from sklearn.model_selection import train_test_split

import config
from modules.feature_extractor import FEATURE_NAMES, features_as_vector


class ModelNotAvailableError(Exception):
    """Raised when the trained model file is missing or unreadable."""


# --------------------------------------------------------------------------
# Synthetic demonstration dataset
# --------------------------------------------------------------------------
_SAFE_HOSTS = ["www.example.com", "example.org", "docs.example.net", "shop.example.com",
               "news.example.org", "blog.example.com", "www.wikipedia.org", "github.com",
               "www.python.org", "stackoverflow.com", "www.mozilla.org", "learn.example.edu"]
_SAFE_PATHS = ["", "/", "/about", "/contact", "/products/item", "/docs/getting-started",
               "/blog/2024/new-features", "/help/faq", "/search?q=books", "/events/schedule",
               "/pricing", "/downloads/readme.pdf"]
_WORDS = ["login", "verify", "account", "secure", "update", "bank", "confirm", "password",
          "wallet", "billing", "support", "signin", "alert", "unlock", "recover"]
_BRANDS = ["paypal", "google", "amazon", "microsoft", "netflix", "apple", "hdfcbank", "facebook"]
_SUSP_TLDS = ["xyz", "top", "tk", "click", "link", "icu", "work"]
_RESERVED = ["test", "example", "invalid"]


def _rand_str(rng: random.Random, n: int) -> str:
    return "".join(rng.choice("abcdefghijklmnopqrstuvwxyz0123456789") for _ in range(n))


def _make_safe(rng: random.Random) -> str:
    scheme = "https" if rng.random() < 0.9 else "http"           # a few safe HTTP links
    url = f"{scheme}://{rng.choice(_SAFE_HOSTS)}{rng.choice(_SAFE_PATHS)}"
    if rng.random() < 0.10:                                     # occasional login page on safe host
        url = f"https://{rng.choice(_SAFE_HOSTS)}/account/login"
    if rng.random() < 0.08:                                     # long, digit-heavy but safe
        url += f"/item/{rng.randint(10000, 99999999)}?ref={_rand_str(rng, 12)}&page={rng.randint(1, 9)}"
    return url


def _make_suspicious(rng: random.Random) -> str:
    kind = rng.choice(["short", "kw", "tld", "port", "hyphen", "redirect", "sub"])
    domain = f"{_rand_str(rng, rng.randint(5, 10))}"
    tld = rng.choice(["com", "net", "org"] + _SUSP_TLDS[:3])
    scheme = "http" if rng.random() < 0.65 else "https"
    if kind == "short":
        return f"https://{rng.choice(['bit.ly', 'tinyurl.com', 'cutt.ly', 'rb.gy'])}/{_rand_str(rng, 6)}"
    if kind == "kw":
        return f"{scheme}://{domain}.{tld}/{rng.choice(_WORDS)}/{rng.choice(_WORDS)}"
    if kind == "tld":
        return f"{scheme}://{domain}.{rng.choice(_SUSP_TLDS)}/"
    if kind == "port":
        return f"{scheme}://{domain}.{tld}:{rng.choice([8080, 8443, 3000, 9000])}/{rng.choice(_WORDS)}"
    if kind == "hyphen":
        return f"{scheme}://{domain}-{rng.choice(_WORDS)}-{rng.choice(_WORDS)}.{tld}/"
    if kind == "redirect":
        return f"{scheme}://{domain}.{tld}/go?url=https://{rng.choice(_SAFE_HOSTS)}&next=/home"
    return f"{scheme}://{rng.choice(_WORDS)}.{domain}.{rng.choice(_RESERVED)}.{tld}/index"


def _make_malicious(rng: random.Random) -> str:
    kind = rng.choice(["ip", "typo", "at", "puny", "multi", "exe", "brandsub"])
    scheme = "http" if rng.random() < 0.8 else "https"
    brand = rng.choice(_BRANDS)
    if kind == "ip":
        ip = ".".join(str(rng.randint(1, 254)) for _ in range(4))
        return f"http://{ip}:{rng.choice([80, 8080, 8888])}/{rng.choice(_WORDS)}/{rng.choice(_WORDS)}.php"
    if kind == "typo":
        typo = brand.replace("o", "0").replace("l", "1") if rng.random() < 0.5 else brand + "-" + rng.choice(_WORDS)
        return f"{scheme}://{typo}-{rng.choice(_WORDS)}.{rng.choice(_SUSP_TLDS)}/{rng.choice(_WORDS)}?id={rng.randint(1000, 99999)}"
    if kind == "at":
        return f"{scheme}://{brand}.com@{_rand_str(rng, 8)}.{rng.choice(_RESERVED)}/{rng.choice(_WORDS)}"
    if kind == "puny":
        return f"https://xn--{_rand_str(rng, 6)}-{_rand_str(rng, 3)}.example/{rng.choice(_WORDS)}/{rng.choice(_WORDS)}"
    if kind == "multi":
        return (f"{scheme}://{rng.choice(_WORDS)}.{brand}.{rng.choice(_WORDS)}.{_rand_str(rng, 7)}"
                f".{rng.choice(_RESERVED)}/{rng.choice(_WORDS)}/{rng.choice(_WORDS)}/{rng.choice(_WORDS)}")
    if kind == "exe":
        return f"{scheme}://{_rand_str(rng, 8)}.{rng.choice(_SUSP_TLDS)}/download/{rng.choice(['setup', 'invoice', 'update'])}.{rng.choice(['exe', 'apk', 'scr'])}"
    return f"{scheme}://{brand}.{rng.choice(_WORDS)}-{rng.choice(_WORDS)}.{_rand_str(rng, 6)}.{rng.choice(_RESERVED)}/"


def generate_sample_dataset(path: Path = config.DATASET_PATH,
                            rows_per_class: int = config.DATASET_ROWS_PER_CLASS,
                            seed: int = config.ML_RANDOM_STATE) -> Path:
    """Write the SYNTHETIC demo dataset (url,label,source) to `path`."""
    rng = random.Random(seed)
    makers = {"SAFE": _make_safe, "SUSPICIOUS": _make_suspicious, "MALICIOUS": _make_malicious}
    rows: List[Tuple[str, str, str]] = []
    for label, maker in makers.items():
        seen = set()
        while len(seen) < rows_per_class:
            seen.add(maker(rng))
        rows.extend((u, label, "synthetic_demo") for u in seen)
    rng.shuffle(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows, columns=["url", "label", "source"]).to_csv(path, index=False)
    return path


# --------------------------------------------------------------------------
# Dataset loading + feature extraction
# --------------------------------------------------------------------------
def load_dataset(path: Path = config.DATASET_PATH) -> pd.DataFrame:
    """Load and clean the URL dataset. Raises FileNotFoundError / ValueError."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found at {path}. Run: python -m modules.ml_classifier generate")
    df = pd.read_csv(path)
    if not {"url", "label"}.issubset(df.columns):
        raise ValueError("The dataset must contain 'url' and 'label' columns.")
    df = df.dropna(subset=["url", "label"]).copy()
    df["url"] = df["url"].astype(str).str.strip()
    df["label"] = df["label"].astype(str).str.strip().str.upper()
    df = df[df["label"].isin(config.ML_LABELS)].drop_duplicates(subset="url")
    if df["label"].nunique() < 2 or len(df) < 30:
        raise ValueError("The dataset is too small or has fewer than two classes.")
    return df.reset_index(drop=True)


def build_feature_matrix(urls: List[str]) -> np.ndarray:
    """Convert URLs into a 2-D numeric array using FEATURE_NAMES order."""
    return np.array([features_as_vector(u) for u in urls], dtype=float)


# --------------------------------------------------------------------------
# Training + evaluation
# --------------------------------------------------------------------------
def train_model(dataset_path: Path = config.DATASET_PATH,
                model_path: Path = config.MODEL_PATH,
                metrics_path: Path = config.METRICS_PATH) -> Dict:
    """Train a Random Forest, evaluate it on a held-out split, and save both."""
    df = load_dataset(dataset_path)
    X = build_feature_matrix(df["url"].tolist())
    y = np.array(df["label"].tolist())   # plain numpy array (pandas 3 uses Arrow strings)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=config.ML_TEST_SIZE, random_state=config.ML_RANDOM_STATE, stratify=y)

    model = RandomForestClassifier(
        n_estimators=config.ML_N_ESTIMATORS, random_state=config.ML_RANDOM_STATE,
        class_weight="balanced", n_jobs=1)
    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)
    labels = [l for l in config.ML_LABELS if l in set(y)]
    prec, rec, f1, _ = precision_recall_fscore_support(
        y_test, y_pred, labels=labels, average="weighted", zero_division=0)
    per_class = precision_recall_fscore_support(
        y_test, y_pred, labels=labels, average=None, zero_division=0)

    metrics = {
        "accuracy": round(float(accuracy_score(y_test, y_pred)), 4),
        "precision_weighted": round(float(prec), 4),
        "recall_weighted": round(float(rec), 4),
        "f1_weighted": round(float(f1), 4),
        "per_class": {
            lab: {"precision": round(float(per_class[0][i]), 4),
                  "recall": round(float(per_class[1][i]), 4),
                  "f1": round(float(per_class[2][i]), 4),
                  "support": int(per_class[3][i])}
            for i, lab in enumerate(labels)},
        "confusion_matrix": confusion_matrix(y_test, y_pred, labels=labels).tolist(),
        "labels": labels,
        "n_train": int(len(X_train)),
        "n_test": int(len(X_test)),
        "feature_importance": {n: round(float(v), 4) for n, v in
                               sorted(zip(FEATURE_NAMES, model.feature_importances_),
                                      key=lambda t: -t[1])},
        "dataset_sources": sorted(df["source"].unique().tolist()) if "source" in df.columns else ["unknown"],
        "disclaimer": ("Metrics are measured on the dataset used for training/testing. If the "
                       "source is 'synthetic_demo' they only demonstrate the pipeline and are "
                       "NOT real-world detection accuracy."),
    }

    model_path = Path(model_path)
    model_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": model, "feature_names": FEATURE_NAMES, "labels": list(model.classes_)}, model_path)
    Path(metrics_path).write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    return metrics


def load_model(model_path: Path = config.MODEL_PATH) -> Dict:
    """Load the saved model bundle. Raises ModelNotAvailableError if unusable."""
    model_path = Path(model_path)
    if not model_path.exists():
        raise ModelNotAvailableError(
            f"No trained model found at {model_path}. Train one with "
            "'python -m modules.ml_classifier all' or use the button in the app.")
    try:
        bundle = joblib.load(model_path)
        if bundle.get("feature_names") != FEATURE_NAMES:
            raise ModelNotAvailableError(
                "The saved model was trained with a different feature set. Please retrain it.")
        return bundle
    except ModelNotAvailableError:
        raise
    except Exception as exc:
        raise ModelNotAvailableError(f"The model file could not be loaded: {exc}") from exc


def load_metrics(metrics_path: Path = config.METRICS_PATH) -> Optional[Dict]:
    """Return saved evaluation metrics, or None if they do not exist."""
    try:
        return json.loads(Path(metrics_path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def predict_url(url: str, bundle: Dict) -> Dict:
    """Classify one URL. Returns label, class probabilities and an ML danger score (0-100)."""
    model = bundle["model"]
    vec = np.array([features_as_vector(url)], dtype=float)
    probs = model.predict_proba(vec)[0]
    prob_map = {str(cls): float(p) for cls, p in zip(model.classes_, probs)}
    label = str(max(prob_map, key=prob_map.get))
    ml_score = (prob_map.get("SUSPICIOUS", 0.0) * config.SCORING["ml_suspicious_value"]
                + prob_map.get("MALICIOUS", 0.0) * 100)
    return {
        "label": label,
        "probabilities": {k: round(prob_map.get(k, 0.0), 4) for k in config.ML_LABELS},
        "confidence": round(prob_map[label], 4),
        "ml_score": round(ml_score, 1),
    }


def ensure_model() -> Dict:
    """Load the model; if missing, generate the demo dataset (if needed) and train."""
    try:
        return load_model()
    except ModelNotAvailableError:
        if not config.DATASET_PATH.exists():
            generate_sample_dataset()
        train_model()
        return load_model()


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------
def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Dataset generation and model training")
    parser.add_argument("command", choices=["generate", "train", "all"])
    args = parser.parse_args(argv)
    try:
        if args.command in ("generate", "all"):
            path = generate_sample_dataset()
            print(f"[OK] Synthetic DEMO dataset written to {path}")
        if args.command in ("train", "all"):
            m = train_model()
            print(f"[OK] Model trained. Accuracy={m['accuracy']}  F1={m['f1_weighted']}  "
                  f"(dataset: {', '.join(m['dataset_sources'])})")
            print("     NOTE: synthetic data - these numbers are NOT real-world accuracy.")
            print(f"     Saved to {config.MODEL_PATH}")
    except (FileNotFoundError, ValueError) as exc:
        print(f"[ERROR] {exc}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
